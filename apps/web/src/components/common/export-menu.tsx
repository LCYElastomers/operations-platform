"use client";

import { ChevronDown, Download, FileSpreadsheet, FileText, LoaderCircle } from "lucide-react";
import { useEffect, useId, useRef, useState } from "react";

import { Button } from "@/components/ui/button";
import { toast } from "@/components/ui/toast";
import { usePermissions } from "@/features/auth/use-session";
import type { Permission } from "@/lib/permissions";
import {
  describeExportError,
  downloadReport,
  FORMAT_LABELS,
  type ReportContext,
  type ReportFormat,
} from "@/lib/reports";
import { cn } from "@/lib/utils";

type ExportMenuProps = {
  /** The API report key, e.g. "car-dashboard". */
  reportKey: string;
  /** Shown in notifications, e.g. "CAR Dashboard". */
  title: string;
  /** Every permission the export needs (view + export); the menu is hidden without them. The API enforces the same. */
  requires: readonly Permission[];
  /** The screen's current period and filters, read when an export starts. */
  context: () => ReportContext;
  formats?: readonly ReportFormat[];
  /** False while the screen has nothing to export (e.g. still loading). */
  disabled?: boolean;
  className?: string;
};

const ICONS = { pdf: FileText, xlsx: FileSpreadsheet } as const;

/**
 * "Export ▾" with a PDF report and an Excel workbook. The file is generated by
 * the API for exactly the screen's period and filters; the user stays on the
 * page and is told when it is ready or why it failed.
 */
export function ExportMenu({ reportKey, title, requires, context, formats = ["pdf", "xlsx"], disabled, className }: ExportMenuProps) {
  const { has } = usePermissions();
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState<ReportFormat | null>(null);
  const id = useId();
  const root = useRef<HTMLDivElement>(null);
  const trigger = useRef<HTMLButtonElement>(null);
  const items = useRef<(HTMLButtonElement | null)[]>([]);

  useEffect(() => {
    if (!open) return;
    items.current[0]?.focus();
    const onPointer = (event: PointerEvent) => {
      if (root.current && !root.current.contains(event.target as Node)) setOpen(false);
    };
    document.addEventListener("pointerdown", onPointer);
    return () => document.removeEventListener("pointerdown", onPointer);
  }, [open]);

  if (!requires.every((permission) => has(permission))) return null;

  const run = async (format: ReportFormat) => {
    setOpen(false);
    trigger.current?.focus();
    if (busy) return;
    setBusy(format);
    try {
      const name = await downloadReport(reportKey, format, context());
      toast("success", `${FORMAT_LABELS[format]} ready`, name);
    } catch (error) {
      toast("error", `${title} could not be exported`, describeExportError(error));
    } finally {
      setBusy(null);
    }
  };

  const onMenuKey = (event: React.KeyboardEvent) => {
    const index = items.current.findIndex((item) => item === document.activeElement);
    if (event.key === "Escape") {
      event.preventDefault();
      setOpen(false);
      trigger.current?.focus();
    } else if (event.key === "ArrowDown" || event.key === "ArrowUp") {
      event.preventDefault();
      const step = event.key === "ArrowDown" ? 1 : -1;
      items.current[(index + step + formats.length) % formats.length]?.focus();
    } else if (event.key === "Tab") {
      setOpen(false);
    }
  };

  return (
    <div ref={root} className={cn("relative", className)}>
      <Button
        ref={trigger}
        variant="outline"
        size="sm"
        aria-haspopup="menu"
        aria-expanded={open}
        aria-controls={open ? `${id}-menu` : undefined}
        aria-busy={busy !== null}
        disabled={disabled || busy !== null}
        onClick={() => setOpen((current) => !current)}
        className="pointer-coarse:h-11"
      >
        {busy ? <LoaderCircle aria-hidden className="animate-spin" /> : <Download aria-hidden />}
        {busy ? `Generating ${busy === "pdf" ? "PDF" : "Excel"}…` : "Export"}
        {!busy && <ChevronDown aria-hidden />}
      </Button>
      {open && (
        <div
          id={`${id}-menu`}
          role="menu"
          aria-label={`Export ${title}`}
          onKeyDown={onMenuKey}
          className="absolute right-0 z-40 mt-1 w-56 rounded-md border bg-card p-1 shadow-lg"
        >
          {formats.map((format, index) => {
            const Icon = ICONS[format];
            return (
              <button
                key={format}
                ref={(element) => {
                  items.current[index] = element;
                }}
                type="button"
                role="menuitem"
                tabIndex={-1}
                onClick={() => void run(format)}
                className="flex w-full items-center gap-2 rounded-sm px-3 py-2 text-left text-sm hover:bg-muted focus-visible:bg-muted focus-visible:outline-none pointer-coarse:py-3"
              >
                <Icon aria-hidden className="size-4 text-muted-foreground" />
                {FORMAT_LABELS[format]}
              </button>
            );
          })}
        </div>
      )}
    </div>
  );
}
